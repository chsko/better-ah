//! Turns stats into what gets published: the page's JSON and the addon's Lua data file.

use std::fmt::Write;

use serde_json::{json, Map, Value};

use crate::rank::{rank_local, Advice, Hint, Rating};
use crate::stats::Stats;
use crate::tz::oslo_offset;

/// Format version of both outputs.
pub const VERSION: u32 = 1;

fn hour_of(t: i64) -> u32 {
    u32::try_from(t.div_euclid(3600)).unwrap_or(0)
}

/// One hint as a single integer, shared by the page and the addon:
/// `better_by * 16 + advice * 4 + rating`, where `better_by` is 0-999 or 1000 for "no sales
/// expected now", `advice` is 0 wait, 1 post 2h, 2 post 8h, 3 post 24h, and `rating` is
/// 0 best, 1 good, 2 average, 3 slow.
pub fn encode(h: &Hint) -> u32 {
    let rating = match h.rating {
        Rating::Best => 0,
        Rating::Good => 1,
        Rating::Average => 2,
        Rating::Slow => 3,
    };
    let advice = match h.advice {
        Advice::Wait => 0,
        Advice::Post(2) => 1,
        Advice::Post(8) => 2,
        Advice::Post(_) => 3,
    };
    h.better_by.unwrap_or(1000) * 16 + advice * 4 + rating
}

/// Hints run-length encoded as `[count, code, count, code, ...]` (168 hints in total), since
/// most hours repeat the hour before.
pub fn run_lengths(hints: &[Hint]) -> Vec<u32> {
    let mut out: Vec<u32> = Vec::new();
    for h in hints {
        let c = encode(h);
        match out.len() {
            n if n >= 2 && out[n - 1] == c => out[n - 2] += 1,
            _ => out.extend([1, c]),
        }
    }
    out
}

fn round(x: f64, places: i32) -> f64 {
    let f = 10f64.powi(places);
    (x * f).round() / f
}

/// Days of data behind the stats at `now` (whole days, at most 30).
pub fn days_covered(stats: &Stats, now: i64) -> u32 {
    stats.collecting_since.map_or(0, |s| {
        (hour_of(now).saturating_sub(hour_of(s)) / 24).min(30)
    })
}

/// The page's files: `index.json` lists every item that sold at least once in the window
/// (`id: [name, sold, best window start or null]`) plus the metadata, and `items/<id>.json`
/// holds one item's cells that had sales or listings
/// (`[weekday-hour, sales, price, score, min price, supply]`) and, with enough data, its best
/// window start, the best window start of each Oslo day (`dayBest`, Monday first, null for a
/// day without sales), its median sale price (`median`) and run-length encoded hints. Split so a phone only loads the item it
/// opens.
pub fn page_files(stats: &Stats, now: i64, market: &str) -> Vec<(String, Value)> {
    let first = stats.collecting_since.map_or(hour_of(now), hour_of);
    let offset = oslo_offset(now);
    let mut index = Map::new();
    let mut files = Vec::new();
    for (item, rows) in &stats.items {
        let r = rank_local(rows, first, hour_of(now), offset);
        if r.sold == 0 {
            continue;
        }
        let best = r.hints.as_ref().map(|_| r.best_start);
        let name = stats.names.get(item).cloned().flatten();
        index.insert(item.to_string(), json!([name, r.sold, best]));
        let cells: Vec<Value> = r
            .cells
            .iter()
            .enumerate()
            .filter(|(_, c)| c.sales > 0.0 || c.min_price > 0)
            .map(|(w, c)| {
                json!([
                    w,
                    round(c.sales, 2),
                    c.price,
                    round(c.score, 3),
                    c.min_price,
                    round(c.supply, 1)
                ])
            })
            .collect();
        files.push((
            format!("items/{item}.json"),
            json!({
                "item": item,
                "name": name,
                "sold": r.sold,
                "best": best,
                "dayBest": r.hints.as_ref().map(|_| r.day_best),
                "median": r.median_price,
                "cells": cells,
                "hints": r.hints.as_ref().map(|h| run_lengths(h)),
            }),
        ));
    }
    files.insert(
        0,
        (
            "index.json".to_string(),
            json!({
                "version": VERSION,
                "generated": now,
                "market": market,
                "collectingSince": stats.collecting_since,
                "lastExport": stats.last_export,
                "days": days_covered(stats, now),
                "utcOffset": offset,
                "items": index,
            }),
        ),
    );
    files
}

/// The addon's data file: only items with hints. Loaded by Better AH like any addon file,
/// so it uses the addon's namespace and creates no globals.
pub fn lua_data(stats: &Stats, now: i64, market: &str) -> String {
    let first = stats.collecting_since.map_or(hour_of(now), hour_of);
    let offset = oslo_offset(now);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "-- Generated by better-ah-companion (spec #215). Do not edit."
    );
    let _ = writeln!(
        out,
        "-- hints: run lengths {{count, code, ...}} over 168 weekday-hours from Monday 00:00 UTC;"
    );
    let _ = writeln!(
        out,
        "-- dayBest: start of each Oslo day's best window (UTC weekday-hour), Monday first; false = none."
    );
    let _ = writeln!(out, "-- code = betterBy * 16 + advice * 4 + rating (betterBy 0-999, 1000 = none;\n-- advice 0 wait, 1 = 2h, 2 = 8h, 3 = 24h; rating 0 best, 1 good, 2 average, 3 slow).");
    let _ = writeln!(out, "local _, ns = ...");
    let _ = writeln!(out, "ns.SellTimesData = {{");
    let _ = writeln!(out, "  version = {VERSION},");
    let _ = writeln!(out, "  generated = {now},");
    let _ = writeln!(out, "  market = {},", lua_string(market));
    let _ = writeln!(out, "  days = {},", days_covered(stats, now));
    let _ = writeln!(out, "  utcOffset = {offset},");
    let _ = writeln!(out, "  items = {{");
    for (item, rows) in &stats.items {
        let r = rank_local(rows, first, hour_of(now), offset);
        let Some(hints) = r.hints else { continue };
        let days: Vec<String> = r
            .day_best
            .iter()
            .map(|d| d.map_or_else(|| "false".to_string(), |w| w.to_string()))
            .collect();
        let _ = writeln!(
            out,
            "    [{item}] = {{ sold = {}, price = {}, best = {}, dayBest = {{ {} }}, hints = {{",
            r.sold,
            r.cells[r.best_start].price,
            r.best_start,
            days.join(", ")
        );
        let codes: Vec<String> = run_lengths(&hints).iter().map(u32::to_string).collect();
        let mut line = String::from("     ");
        for c in codes {
            if line.len() + c.len() + 2 > 118 {
                let _ = writeln!(out, "{}", line.trim_end());
                line = String::from("     ");
            }
            line.push(' ');
            line.push_str(&c);
            line.push(',');
        }
        let _ = writeln!(out, "{}", line.trim_end());
        let _ = writeln!(out, "    }} }},");
    }
    let _ = writeln!(out, "  }},");
    let _ = writeln!(out, "}}");
    out
}

fn lua_string(s: &str) -> String {
    let mut o = String::from("\"");
    for ch in s.chars() {
        match ch {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c if (c as u32) < 0x20 => {
                let _ = write!(o, "\\{:03}", c as u32);
            }
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn encode_packs_all_three_parts() {
        let h = Hint {
            rating: Rating::Average,
            better_by: Some(40),
            advice: Advice::Post(8),
        };
        assert_eq!(encode(&h), 40 * 16 + 2 * 4 + 2);
        let none = Hint {
            rating: Rating::Slow,
            better_by: None,
            advice: Advice::Wait,
        };
        assert_eq!(encode(&none), 16003);
    }

    #[test]
    fn run_lengths_cover_all_hours_and_round_trip() {
        let a = Hint {
            rating: Rating::Slow,
            better_by: None,
            advice: Advice::Wait,
        };
        let b = Hint {
            rating: Rating::Best,
            better_by: Some(0),
            advice: Advice::Post(2),
        };
        let mut hints = vec![a; 100];
        hints.extend(vec![b; 3]);
        hints.extend(vec![a; 65]);
        let rl = run_lengths(&hints);
        assert_eq!(rl, vec![100, 16003, 3, 4, 65, 16003]);
        let decoded: Vec<u32> = rl
            .chunks(2)
            .flat_map(|p| std::iter::repeat_n(p[1], p[0] as usize))
            .collect();
        assert_eq!(decoded.len(), 168);
        assert_eq!(decoded, hints.iter().map(encode).collect::<Vec<_>>());
        // Every code decodes back to its parts.
        for code in decoded {
            assert!(code % 4 <= 3 && (code / 4) % 4 <= 3 && code / 16 <= 1000);
        }
    }

    #[test]
    fn lua_strings_are_escaped() {
        assert_eq!(lua_string("/Normal/Horde"), "\"/Normal/Horde\"");
        assert_eq!(lua_string("a\"b\\c\n"), "\"a\\\"b\\\\c\\n\"");
        assert_eq!(lua_string("\u{1}2"), "\"\\0012\"");
    }
}
