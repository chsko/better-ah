//! `sync`: copies the addon's sell times data file from the Pages site into the BetterAH
//! folder (spec #215, #220). Shared by the console binary and the windowless task binary.

use std::fs;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::time::Duration;

pub type Res<T> = Result<T, String>;

/// Where `collect` publishes the addon data file.
pub const DEFAULT_URL: &str = "https://chsko.github.io/better-ah/SellTimes.lua";
/// The data file's name inside the BetterAH folder; listed in BetterAH.toc and gitignored.
pub const FILE_NAME: &str = "SellTimes.lua";
/// Far above any real file (a few MB at most); stops a runaway download.
const MAX_BYTES: u64 = 64 * 1024 * 1024;

/// Something that can fetch a URL; the real one is HTTP, tests use a fake.
pub trait Source {
    fn get(&self, url: &str) -> Res<Vec<u8>>;
}

/// Fetches over HTTPS.
pub struct Http;

impl Source for Http {
    fn get(&self, url: &str) -> Res<Vec<u8>> {
        let agent = ureq::AgentBuilder::new()
            .timeout_connect(Duration::from_secs(15))
            .timeout(Duration::from_secs(120))
            .user_agent("better-ah-companion")
            .build();
        let resp = agent.get(url).call().map_err(|e| match e {
            ureq::Error::Status(code, _) => format!("{url} answered HTTP {code}"),
            other => format!("{url}: {other}"),
        })?;
        let mut body = Vec::new();
        resp.into_reader()
            .take(MAX_BYTES + 1)
            .read_to_end(&mut body)
            .map_err(|e| format!("{url}: {e}"))?;
        if body.len() as u64 > MAX_BYTES {
            return Err(format!("{url}: file is larger than {MAX_BYTES} bytes"));
        }
        Ok(body)
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum Outcome {
    /// The file was new or changed and has been replaced.
    Written(usize),
    /// The file on disk already had the same content.
    Unchanged,
}

/// Checks that `dir` is the BetterAH addon folder, so `sync` never writes anywhere else.
pub fn check_target(dir: &Path) -> Res<()> {
    if dir.join("BetterAH.toc").is_file() {
        Ok(())
    } else {
        Err(format!(
            "{} is not the BetterAH addon folder (no BetterAH.toc in it)",
            dir.display()
        ))
    }
}

/// Checks that a download is a data file written by `collect`, not an error page.
pub fn check_data(body: &[u8]) -> Res<()> {
    let text = std::str::from_utf8(body).map_err(|_| "downloaded file is not UTF-8 text")?;
    let ok = text.starts_with("-- Generated by better-ah-companion")
        && text.contains("\nlocal _, ns = ...\nns.SellTimesData = {\n")
        // The exact tail `lua_data` writes, so a download cut off mid-way is refused.
        && text.ends_with("\n  },\n}\n");
    if ok {
        Ok(())
    } else {
        Err("downloaded file is not a Better AH sell times data file".into())
    }
}

/// Downloads the data file and puts it into `dir` (the BetterAH folder). Writes a temp file
/// first and renames it over the old one, so the game never loads a half-written file, and
/// leaves the file alone when nothing changed.
pub fn sync(source: &dyn Source, url: &str, dir: &Path) -> Res<Outcome> {
    check_target(dir)?;
    let body = source.get(url)?;
    check_data(&body)?;
    let path = dir.join(FILE_NAME);
    if fs::read(&path).is_ok_and(|old| old == body) {
        return Ok(Outcome::Unchanged);
    }
    let tmp = dir.join(format!("{FILE_NAME}.tmp"));
    fs::write(&tmp, &body).map_err(|e| format!("write {}: {e}", tmp.display()))?;
    // On Windows std's rename replaces an existing file (MOVEFILE_REPLACE_EXISTING). A virus
    // scanner or the search indexer can hold the file for a moment, so try a few times.
    let mut tries = 0;
    while let Err(e) = fs::rename(&tmp, &path) {
        tries += 1;
        if tries == 3 {
            let _ = fs::remove_file(&tmp);
            return Err(format!("replace {}: {e}", path.display()));
        }
        std::thread::sleep(Duration::from_millis(300));
    }
    Ok(Outcome::Written(body.len()))
}

/// `sync`'s options, shared by both binaries.
pub struct SyncArgs {
    pub url: String,
    pub target: PathBuf,
}

/// The default BetterAH folder: `%USERPROFILE%\better-ah\BetterAH`, the repo clone the
/// AddOns junction points at.
pub fn default_target() -> Option<PathBuf> {
    std::env::var_os("USERPROFILE")
        .map(|home| PathBuf::from(home).join("better-ah").join("BetterAH"))
}

pub fn parse_sync_args(args: &[String]) -> Res<SyncArgs> {
    let mut url = DEFAULT_URL.to_string();
    let mut target = None;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        let mut value = || it.next().cloned().ok_or(format!("{a} needs a value"));
        match a.as_str() {
            "--url" => url = value()?,
            "--target" => target = Some(PathBuf::from(value()?)),
            _ => return Err(format!("unknown argument {a}")),
        }
    }
    let target = target
        .or_else(default_target)
        .ok_or("--target <BetterAH folder> is required")?;
    Ok(SyncArgs { url, target })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::cell::Cell;

    const DATA: &str = "-- Generated by better-ah-companion (spec #215). Do not edit.\n\
        local _, ns = ...\nns.SellTimesData = {\n  version = 1,\n  items = {\n  },\n}\n";

    struct Fake {
        body: Res<Vec<u8>>,
        calls: Cell<u32>,
    }

    impl Fake {
        fn ok(s: &str) -> Fake {
            Fake {
                body: Ok(s.as_bytes().to_vec()),
                calls: Cell::new(0),
            }
        }
    }

    impl Source for Fake {
        fn get(&self, _url: &str) -> Res<Vec<u8>> {
            self.calls.set(self.calls.get() + 1);
            self.body.clone()
        }
    }

    fn addon_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("bah-sync-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("BetterAH.toc"), "## Title: Better AH\n").unwrap();
        dir
    }

    #[test]
    fn writes_the_file_into_the_addon_folder_without_leaving_a_temp_file() {
        let dir = addon_dir("write");
        let out = sync(&Fake::ok(DATA), DEFAULT_URL, &dir).unwrap();
        assert_eq!(out, Outcome::Written(DATA.len()));
        assert_eq!(fs::read_to_string(dir.join(FILE_NAME)).unwrap(), DATA);
        assert!(!dir.join("SellTimes.lua.tmp").exists());
    }

    #[test]
    fn skips_the_write_when_nothing_changed() {
        let dir = addon_dir("same");
        fs::write(dir.join(FILE_NAME), DATA).unwrap();
        let before = fs::metadata(dir.join(FILE_NAME))
            .unwrap()
            .modified()
            .unwrap();
        assert_eq!(
            sync(&Fake::ok(DATA), DEFAULT_URL, &dir).unwrap(),
            Outcome::Unchanged
        );
        let after = fs::metadata(dir.join(FILE_NAME))
            .unwrap()
            .modified()
            .unwrap();
        assert_eq!(before, after);
    }

    #[test]
    fn replaces_an_older_file() {
        let dir = addon_dir("replace");
        fs::write(dir.join(FILE_NAME), "old").unwrap();
        sync(&Fake::ok(DATA), DEFAULT_URL, &dir).unwrap();
        assert_eq!(fs::read_to_string(dir.join(FILE_NAME)).unwrap(), DATA);
    }

    #[test]
    fn refuses_a_folder_that_is_not_betterah_and_does_not_download() {
        let dir = addon_dir("wrong");
        fs::remove_file(dir.join("BetterAH.toc")).unwrap();
        let fake = Fake::ok(DATA);
        assert!(sync(&fake, DEFAULT_URL, &dir).is_err());
        assert_eq!(fake.calls.get(), 0);
        assert!(!dir.join(FILE_NAME).exists());
    }

    #[test]
    fn keeps_the_old_file_when_the_download_is_not_a_data_file() {
        let dir = addon_dir("html");
        fs::write(dir.join(FILE_NAME), DATA).unwrap();
        let err = sync(&Fake::ok("<!doctype html><h1>404</h1>"), DEFAULT_URL, &dir).unwrap_err();
        assert!(err.contains("not a Better AH"), "{err}");
        // A file cut off mid-way is refused too.
        assert!(sync(&Fake::ok(&DATA[..DATA.len() - 3]), DEFAULT_URL, &dir).is_err());
        let cut = DATA.replace(
            "  items = {\n  },\n}\n",
            "  items = {\n    [1] = { sold = 1, hints = {\n    } }",
        );
        assert!(sync(&Fake::ok(&cut), DEFAULT_URL, &dir).is_err());
        assert_eq!(fs::read_to_string(dir.join(FILE_NAME)).unwrap(), DATA);
    }

    #[test]
    fn keeps_the_old_file_when_the_download_fails() {
        let dir = addon_dir("fail");
        fs::write(dir.join(FILE_NAME), DATA).unwrap();
        let fake = Fake {
            body: Err("HTTP 503".into()),
            calls: Cell::new(0),
        };
        assert!(sync(&fake, DEFAULT_URL, &dir).is_err());
        assert_eq!(fs::read_to_string(dir.join(FILE_NAME)).unwrap(), DATA);
    }

    #[test]
    fn the_golden_data_file_passes_the_check() {
        let golden = include_str!("../../core/tests/golden/SellTimes.lua");
        assert!(check_data(golden.as_bytes()).is_ok());
    }

    #[test]
    fn parses_target_and_url() {
        let a = parse_sync_args(&[
            "--target".into(),
            "D:\\x\\BetterAH".into(),
            "--url".into(),
            "http://h/f".into(),
        ])
        .unwrap();
        assert_eq!(a.target, PathBuf::from("D:\\x\\BetterAH"));
        assert_eq!(a.url, "http://h/f");
        assert!(parse_sync_args(&["--nope".into()]).is_err());
    }
}
