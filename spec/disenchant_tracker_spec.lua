local helper = require("spec.helper")

describe("DisenchantTracker (#256)", function()
  local ns = helper.load("BetterAH/Core/Purchases.lua")
  helper.load("BetterAH/Core/Disenchant.lua", ns)
  local Tracker = helper.load("BetterAH/Core/DisenchantTracker.lua", ns).DisenchantTracker
  local DE = Tracker.SPELL
  local green = "|cff1eff00|Hitem:4251:0:0:0:0:0:-34:0|h[Hillman's Shoulders]|h|r"
  local dust = "|cffffffff|Hitem:10940::::::::60|h[Strange Dust]|h|r"
  local essence = "|cff1eff00|Hitem:10998::::::::60|h[Lesser Astral Essence]|h|r"

  it("pairs the item used just before a Disenchant with the loot that follows", function()
    local tr = Tracker.new()
    tr:used(10, green)
    tr:started(10.1, "c1", DE)
    tr:succeeded(13, "c1", DE)
    local got = tr:loot(13.5, { { link = dust, count = 3 }, { link = essence, count = 1 } })
    assert.same({ item = 4251, suffix = -34, link = green, mats = { [10940] = 3, [10998] = 1 } }, got)
    assert.is_nil(tr:loot(14, { { link = dust, count = 3 } }), "one loot per disenchant")
  end)

  it("prefers the item locked when the cast started over the last item used", function()
    local tr = Tracker.new()
    tr:used(10, "|Hitem:5555::::|h[Potion]|h")
    tr:started(10.1, "c1", DE, green)
    tr:succeeded(13, "c1", DE)
    assert.equal(4251, tr:loot(13.2, { { link = dust, count = 1 } }).item)
  end)

  it("prefers the loot's own source item over both", function()
    local tr = Tracker.new()
    tr:started(10.1, "c1", DE, "|Hitem:7777::::|h[Other]|h")
    tr:succeeded(13, "c1", DE)
    assert.equal(4251, tr:loot(13.2, { { link = dust, count = 1 } }, green).item)
  end)

  it("ignores an item used long before the cast started, as another spell's target", function()
    local tr = Tracker.new()
    tr:used(1, green)
    tr:started(10, "c1", DE)
    tr:succeeded(13, "c1", DE)
    local got, why = tr:loot(13.2, { { link = dust, count = 1 } })
    assert.is_nil(got)
    assert.equal("no item", why)
  end)

  it("takes an item used shortly before a cast whose start was missed", function()
    local tr = Tracker.new()
    tr:used(10, green)
    tr:succeeded(13, "c1", DE)
    assert.equal(4251, tr:loot(13.2, { { link = dust, count = 1 } }).item)
  end)

  it("keeps a cast's item when a second press of Disenchant fails", function()
    local tr = Tracker.new()
    tr:started(10, "c1", DE, green)
    tr:failed("c2", DE)
    tr:succeeded(13, "c1", DE)
    assert.equal(4251, tr:loot(13.2, { { link = dust, count = 1 } }).item)
  end)

  it("drops the item of a cast that failed", function()
    local tr = Tracker.new()
    tr:started(10, "c1", DE, green)
    tr:failed("c1", DE)
    tr:started(20, "c2", DE)
    tr:succeeded(23, "c2", DE)
    assert.is_nil(tr:loot(23.2, { { link = dust, count = 1 } }))
  end)

  it("ignores loot when no disenchant just finished", function()
    local tr = Tracker.new()
    assert.is_nil(tr:loot(5, { { link = dust, count = 2 } }))
    tr:used(9, green)
    tr:succeeded(10, "c1", 133) -- a Fireball
    assert.is_nil(tr:loot(11, { { link = dust, count = 2 } }))
  end)

  it("lets a disenchant's loot go after WINDOW seconds, and never takes loot from before it", function()
    local tr = Tracker.new()
    tr:started(10, "c1", DE, green)
    tr:succeeded(13, "c1", DE)
    assert.is_nil(tr:loot(12, { { link = dust, count = 2 } }))
    tr:started(20, "c2", DE, green)
    tr:succeeded(23, "c2", DE)
    assert.is_nil(tr:loot(23 + Tracker.WINDOW + 1, { { link = dust, count = 2 } }))
  end)

  it("keeps only disenchant mats, and needs at least one", function()
    local tr = Tracker.new()
    tr:started(10, "c1", DE, green)
    tr:succeeded(13, "c1", DE)
    local got, why = tr:loot(13.2, { { link = "|Hitem:2589::::|h[Linen Cloth]|h", count = 2 } })
    assert.is_nil(got)
    assert.equal("no mats", why)
  end)

  it("adds up a mat spread over several loot slots", function()
    local tr = Tracker.new()
    tr:started(10, "c1", DE, green)
    tr:succeeded(13, "c1", DE)
    local got = tr:loot(13.2, { { link = dust, count = 2 }, { link = dust, count = 1 }, { link = nil, count = 4 } })
    assert.same({ [10940] = 3 }, got.mats)
  end)
end)
